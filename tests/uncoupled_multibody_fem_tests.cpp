// Pass21: two independently physically integrated neo-Hookean FEM
// bodies, one shared real finite rigid triangular obstacle, and one
// union feature mesh. This is a source-adapter/candidate test.
// Crucially this does NOT solve deformable/deformable collision response.
#include "kyoto/multi_body_fem_snapshots.hpp"
#include "kyoto/refit_feature_hierarchy.hpp"
#include <cmath>
#include <cstdint>
#include <iostream>
#include <stdexcept>

namespace f=kyoto::contact::features;
namespace s=kyoto::solid;
namespace fem=kyoto::contact::fem;
using kyoto::contact::atlas::RefitHierarchy;

static void need(bool ok,const char* message){
    if(!ok)throw std::runtime_error(message);
}
static void move_x(s::Body& b,double offset){
    for(auto& n:b.nodes) {
        n.x.x+=offset;
        n.rest.x+=offset;
    }
}
static void match(RefitHierarchy& hierarchy,RefitHierarchy& selective,
                  const f::Mesh& mesh,const char* stage){
    const auto truth=f::exhaustive(mesh).pairs;
    const auto sap=f::sweep_and_prune(mesh).pairs;
    const auto plain=hierarchy.query(mesh).pairs;
    const auto dirty=selective.query(mesh).pairs;
    if(plain!=truth||dirty!=truth||sap!=truth)
        throw std::runtime_error(std::string(stage)+
            ": independently integrated multibody VF/EE oracle mismatch");
}
int main(){
 try{
    auto a=s::toroidal_solid(8),b=s::toroidal_solid(10);
    move_x(a,-1.3);move_x(b,+1.3);
    for(auto& n:a.nodes)n.v={+.03,+.02,0.};
    for(auto& n:b.nodes)n.v={-.03,-.02,0.};
    const auto rigid=s::corrugated_contact_patch();
    RefitHierarchy plain(true,false),selective(true,false,false,4,true);
    for(int step=0;step<4;++step){
        const s::Body before_a=a,before_b=b;
        const auto moved_a=s::step_time_consistent_rigid_triangle_mesh(
            a,rigid,.00075);
        const auto moved_b=s::step_time_consistent_rigid_triangle_mesh(
            b,rigid,.00075);
        need(moved_a.accepted_leaves>=1 && moved_b.accepted_leaves>=1,
             "one original physical FEM source body did not integrate");
        need(std::abs(a.time_seconds-b.time_seconds)<1e-12,
             "two physical source FEM bodies lost synchronized time");
        need(moved_a.accepted_leaves==1 && moved_b.accepted_leaves==1,
             "source must expose one true accepted linear physical leaf each");
        const double gap=fem::uncoupled_two_body_swept_x_gap(
            before_a,a,before_b,b);
        need(std::isfinite(gap)&&gap>.002,
             "physical cross-body swept motion is not disjoint");
        // Negative safety control: a geometrically overlapping body
        // cannot use the uncoupled evidence protocol.
        auto intruding_before_b=before_b,intruding_after_b=b;
        for(auto& n:intruding_before_b.nodes)n.x.x-=2.5;
        for(auto& n:intruding_after_b.nodes)n.x.x-=2.5;
        need(fem::uncoupled_two_body_swept_x_gap(
                 before_a,a,intruding_before_b,intruding_after_b)<=0,
             "unsupported mutual collision escaped sufficient x-axis gate");
        const auto mesh=fem::uncoupled_two_body_feature_snapshot(
            before_a,a,before_b,b,rigid);
        const auto va=a.nodes.size(),vb=b.nodes.size();
        need(mesh.vertices.size()==va+vb+rigid.vertices.size(),
             "union source lost one physically integrated object's vertices");
        need(mesh.faces.size()==a.surface_faces.size()+
                                   b.surface_faces.size()+rigid.faces.size(),
             "union source lost real source faces");
        for(std::size_t i=0;i<va;++i)
            need(mesh.vertices[i].id==i&&mesh.vertices[i].object==0,
                 "first physical body IDs or object labels changed");
        for(std::size_t i=0;i<vb;++i)
            need(mesh.vertices[va+i].id==va+i&&
                 mesh.vertices[va+i].object==1,
                 "second physical body IDs/object labels collide");
        for(std::size_t i=0;i<rigid.vertices.size();++i)
            need(mesh.vertices[va+vb+i].object==2,
                 "static rigid object labels overlap moving body IDs");
        match(plain,selective,mesh,"original two-body physical step");
        const double a_dx=std::abs(a.nodes[0].x.x-before_a.nodes[0].x.x);
        const double b_dx=std::abs(b.nodes[0].x.x-before_b.nodes[0].x.x);
        need(a_dx>1e-8&&b_dx>1e-8,
             "multibody source motion not generated by physical solver");

        if(step==0) {
            auto modified=mesh;
            modified.vertices[1].mask=0;
            match(plain,selective,modified,
                  "same-epoch cross-object collision mask invalidation");
            // Reinstating the input mask also forces safe topology rebuild.
            match(plain,selective,mesh,
                  "full independent collision-mask restoration");
            auto invalid=mesh;
            invalid.faces.back().vertices[0]=
                std::uint64_t(mesh.vertices.size()+1234);
            bool rejected=false;
            try{
                (void)fem::uncoupled_two_body_feature_snapshot(
                    before_a,a,before_b,b,rigid,-.1);
            }catch(const std::invalid_argument&){rejected=true;}
            need(rejected,"invalid multibody source skin was accepted");
            (void)invalid; // Invalid connectivity separately covered by f::build.
        }
    }
    std::cout<<"PASS21 two REAL independently integrated FEM bodies plus "
             <<"finite static triangular obstacle; unique multiobject "
             <<"IDs; exact rebuilt SAP/full/dirty BVH VF/EE oracle parity. "
             <<"No body-body physical contact response claimed.\n";
    return 0;
 }catch(const std::exception& e){
    std::cerr<<"PASS21 multibody source FAIL: "<<e.what()<<'\n';
    return 1;
 }
}
